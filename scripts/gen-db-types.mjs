#!/usr/bin/env node
/**
 * Generates lib/database.types.ts from a database that has the migrations
 * applied, in the same shape as `supabase gen types typescript`.
 *
 * Usage: DATABASE_URL=postgres://... node scripts/gen-db-types.mjs
 * (With a linked Supabase project you can use the official command instead:
 *  npx supabase gen types typescript --linked > lib/database.types.ts
 *  then re-add the helper types at the bottom of the file.)
 */
import { writeFileSync } from "node:fs";
import pg from "pg";

const url = process.env.DATABASE_URL ?? process.env.TEST_DATABASE_URL;
if (!url) {
  console.error("Set DATABASE_URL to a database with the migrations applied.");
  process.exit(1);
}

const TYPE_MAP = {
  uuid: "string",
  text: "string",
  varchar: "string",
  date: "string",
  time: "string",
  timestamptz: "string",
  timestamp: "string",
  int2: "number",
  int4: "number",
  int8: "number",
  numeric: "number",
  float4: "number",
  float8: "number",
  bool: "boolean",
  jsonb: "Json",
  json: "Json",
};

function tsType(udt) {
  if (udt.startsWith("_")) return `${tsType(udt.slice(1))}[]`;
  return TYPE_MAP[udt] ?? "unknown";
}

const client = new pg.Client({ connectionString: url });
await client.connect();

const { rows: columns } = await client.query(`
  select c.table_name, c.column_name, c.udt_name, c.is_nullable = 'YES' as nullable,
         c.column_default is not null or c.is_identity = 'YES' as has_default
  from information_schema.columns c
  join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
  where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
  order by c.table_name, c.ordinal_position`);

const { rows: functions } = await client.query(`
  select p.proname as name,
         coalesce(p.proargnames, '{}') as arg_names,
         coalesce(p.proargmodes::text[], '{}') as arg_modes,
         array(select format_type(t, null) from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) t) as arg_types,
         p.pronargdefaults as n_defaults,
         p.pronargs as n_in,
         format_type(p.prorettype, null) as return_type,
         p.proretset as returns_set
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public'
    and p.prorettype <> 'trigger'::regtype
    and p.proname not in ('set_updated_at')
  order by p.proname`);

await client.end();

const FORMAT_MAP = {
  uuid: "string",
  text: "string",
  date: "string",
  "timestamp with time zone": "string",
  integer: "number",
  bigint: "number",
  numeric: "number",
  boolean: "boolean",
  jsonb: "Json",
  void: "undefined",
};
const fmt = (t) => (t.endsWith("[]") ? `${fmt(t.slice(0, -2))}[]` : (FORMAT_MAP[t] ?? "unknown"));

const tables = new Map();
for (const col of columns) {
  if (!tables.has(col.table_name)) tables.set(col.table_name, []);
  tables.get(col.table_name).push(col);
}

const ind = (n) => " ".repeat(n);
let out = `/**
 * Database types. GENERATED by scripts/gen-db-types.mjs (same shape as
 * \`supabase gen types typescript\`). Don't edit by hand; regenerate after
 * adding a migration: DATABASE_URL=... npm run db:types
 */
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
`;

for (const [table, cols] of tables) {
  out += `${ind(6)}${table}: {\n`;
  out += `${ind(8)}Row: {\n`;
  for (const c of cols) out += `${ind(10)}${c.column_name}: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""};\n`;
  out += `${ind(8)}};\n${ind(8)}Insert: {\n`;
  for (const c of cols) {
    const optional = c.nullable || c.has_default ? "?" : "";
    out += `${ind(10)}${c.column_name}${optional}: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""};\n`;
  }
  out += `${ind(8)}};\n${ind(8)}Update: {\n`;
  for (const c of cols) out += `${ind(10)}${c.column_name}?: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""};\n`;
  out += `${ind(8)}};\n${ind(8)}Relationships: [];\n${ind(6)}};\n`;
}

out += `${ind(4)}};\n${ind(4)}Views: { [_ in never]: never };\n${ind(4)}Functions: {\n`;
for (const f of functions) {
  const inputs = [];
  const outputs = [];
  f.arg_names.forEach((name, i) => {
    const mode = f.arg_modes[i] ?? "i";
    const type = fmt(f.arg_types[i]);
    if (mode === "t" || mode === "o") outputs.push(`${name}: ${type}`);
    else inputs.push({ name, type, index: i });
  });
  const firstDefault = f.n_in - f.n_defaults;
  const args = inputs.map((a) => `${a.name}${a.index >= firstDefault ? "?" : ""}: ${a.type}`).join("; ");
  let ret;
  if (outputs.length) ret = `{ ${outputs.join("; ")} }[]`;
  else if (f.returns_set) ret = "unknown[]";
  else ret = fmt(f.return_type);
  out += `${ind(6)}${f.name}: { Args: ${args ? `{ ${args} }` : "Record<PropertyKey, never>"}; Returns: ${ret} };\n`;
}
out += `${ind(4)}};
    Enums: { [_ in never]: never };
    CompositeTypes: { [_ in never]: never };
  };
};

export type Tables<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Row"];
export type TablesInsert<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Insert"];
`;

writeFileSync(new URL("../lib/database.types.ts", import.meta.url), out);
console.log(`Wrote lib/database.types.ts (${tables.size} tables, ${functions.length} functions).`);
